// Цифровые клавиши
#define IR_KEY_0 0x68  // Было 0x16 (00010110 -> 01101000)
#define IR_KEY_1 0x30  // Было 0x0C (00001100 -> 00110000)
#define IR_KEY_2 0x18  // Было 0x18 (00011000 -> 00011000 - симметричный байт)
#define IR_KEY_3 0x7A  // Было 0x5E (01011110 -> 01111010)
#define IR_KEY_4 0x10  // Было 0x08 (00001000 -> 00010000)
#define IR_KEY_5 0x38  // Было 0x1C (00011100 -> 00111000)
#define IR_KEY_6 0x5A  // Было 0x5A (01011010 -> 01011010 - симметричный байт)
#define IR_KEY_7 0x42  // Было 0x42 (01000010 -> 01000010 - симметричный байт)
#define IR_KEY_8 0x4A  // Было 0x52 (01010010 -> 01001010)
#define IR_KEY_9 0x52  // Было 0x4A (01001010 -> 01010010)

// Функциональные клавиши
#define IR_KEY_POWER       0xA2  // Было 0x45 (01000101 -> 10100010)
#define IR_KEY_MODE        0x62  // Было 0x46 (01000110 -> 01100010)
#define IR_KEY_MUTE        0xE2  // Было 0x47 (01000111 -> 11100010)
#define IR_KEY_PLAY_PAUSE  0x22  // Было 0x44 (01000100 -> 00100010)
#define IR_KEY_PREV        0x02  // Было 0x40 (01000000 -> 00000010)
#define IR_KEY_NEXT        0xC2  // Было 0x43 (01000011 -> 11000010)
#define IR_KEY_EQ          0xE0  // Было 0x07 (00000111 -> 11100000)
#define IR_KEY_VOLUME_DOWN 0xA8  // Было 0x15 (00010101 -> 10101000)
#define IR_KEY_VOLUME_UP   0x90  // Было 0x09 (00001001 -> 10010000)
#define IR_KEY_REPEAT      0x98  // Было 0x19 (00011001 -> 10011000)
#define IR_KEY_SCAN        0xB0  // Было 0x0D (00001101 -> 10110000)

// *********************************************************************************
// СТРУКТУРА ИК-КАДРА СТАНДАРТНОГО ПРОТОКОЛА NEC
// *********************************************************************************
//
// Передача ведётся несущей частотой 38 кГц. Демодулятор ИК-приёмника инвертирует 
// сигнал: наличие излучения выдаёт на пин STM32 уровень LOW, тишина — уровень HIGH. 
// Протокол кодируется длительностью пауз (Space encoding).
//
// Шаг счётчика TIM2 настроен на 1 мкс. Входной захват работает в Reset Mode:
// - Импульс LOW (передатчик излучает) -> ловится в TIM2->CCR2 (переменная lsi)
// - Полный период (Импульс + Пауза)   -> ловится в TIM2->CCR1 (переменная total_period)
// - Пауза HIGH (передатчик молчит)    -> вычисляется как hsi = total_period - lsi
//
// 1. ПОЛНОЦЕННЫЙ ИК-ПАКЕТ ДАННЫХ (Передаётся один раз при нажатии):
// =================================================================================
// [Старт-бит (Leader)] [32 бита данных (Адрес, инверсия, Команда, инверсия)] [Стоп-бит]
//
// • Стартовый импульс (Leader Mark) : ~9000 мкс LOW  (Допуск: 8000..10000 мкс)
// • Стартовая пауза  (Header Space) : ~4500 мкс HIGH (Допуск: 3800..5200 мкс)
//
// • Логический '0' (Длина шага ~1125 мкс):
//   - Маркер (импульс) : ~560 мкс LOW
//   - Пауза (тишина)   : ~560 мкс HIGH (Допуск: 300..900 мкс)
//
// • Логическая '1' (Длина шага ~2250 мкс):
//   - Маркер (импульс) : ~560 мкс LOW
//   - Пауза (тишина)   : ~1690 мкс HIGH (Допуск: 1300..2000 мкс)
//
// • Финальный стоп-маркер : ~560 мкс LOW, после чего линия уходит в HIGH (тишина).
//
// 2. ПАКЕТ ПОВТОРА (NEC REPEAT / HOLD) (Передаётся каждые 110 мс при удержании):
// =================================================================================
// Используется для разгрузки эфира. Вместо повторения 32 бит данных шлется маркер:
//
// • Повторный импульс (Repeat Mark)  : ~9000 мкс LOW  (Допуск: 8000..10000 мкс)
// • Повторная пауза   (Repeat Space) : ~2250 мкс HIGH (Допуск: 1800..2700 мкс)
// • Стоп-маркер                      : ~560 мкс LOW
//
// 3. ФИЗИЧЕСКИЙ ПОРЯДОК СЛЕДОВАНИЯ БАЙТ В СТАНДАРТЕ NEC (LSB First):
// =================================================================================
// По воздуху биты идут младшим битом вперёд. Временная шкала слева направо:
//
// |-- Старт-бит --|--- Байт 0 ---|--- Байт 1 ---|--- Байт 2 ---|--- Байт 3 ---|
// |               |              |              |              |              |
// |  [Leader]     |  [Address]   |  [Address_]  |  [Command]   |  [Command_]  |
// |               |  bit0..bit7  |  bit0..bit7  |  bit0..bit7  |  bit0..bit7  |
//
// 4. СТРУКТУРА ПЕРЕМЕННОЙ `stor` ПОСЛЕ СДВИГА ВЛЕВО `(stor << 1)`:
// =================================================================================
// Так как алгоритм AVI-crak проталкивает биты влево, первый пришедший бит (bit 0 
// адреса) в конце приёма оказывается в самом старшем 31-м бите переменной `stor`. 
// В результате байты внутри регистров процессора STM32 выстраиваются зеркально:
//
// Bits: 31             24 23             16 15              8 7              0
//       |                |                 |                  |                 |
// stor: [ Command_Inv ]  |  [  Command  ]  |  [ Address_Inv ] |  [  Address  ]  |
//
// Маски для извлечения байт в прерывании:
// - command_inv = (uint8_t)(stor >> 24); -> Инверсный байт команды пульта
// - command     = (uint8_t)(stor >> 16); -> Реальный байт команды (зеркальный)
// - address_inv = (uint8_t)(stor >> 8);  -> Инверсный байт адреса пульта
// - address     = (uint8_t)(stor);       -> Реальный байт адреса (зеркальный)
//
// *********************************************************************************


// ============================================================================
// ГЛОБАЛЬНЫЕ ПЕРЕМЕННЫЕ
